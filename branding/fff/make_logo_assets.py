#!/usr/bin/env python3
"""Build every FfF logo asset the app needs from one square logo image.

Usage (from the repository root, needs Python 3 with Pillow: pip install pillow):
    python3 branding/fff/make_logo_assets.py branding/fff/fff_logo_source.png

The source is the round Foundations for Farming logo on a plain light background.
The script finds the round logo, cuts it out with a transparent background, and writes:

  branding/fff/fff_logo_round.png                         the cut-out logo (transparent corners)
  branding/fff/fff_logo.svg                               in-app logo (welcome screen, About), PNG embedded
  images/icons/qfieldcloud_logo.svg                       logo on the cloud sign-in screen (replaces QFieldCloud's)
  images/icons/nyuki.svg                                  default account picture (replaces QFieldCloud's mascot)
  platform/android/res/drawable-nodpi/fff_logo_fg.png     launcher icon foreground (432x432, logo in the safe zone)
  platform/android/res/drawable-nodpi/fff_logo_splash.png splash screen image
  platform/android/res/drawable/launcher_fff_logo*.xml    adaptive launcher icon (white background, logo, droplet mono icon)
  platform/android/res/drawable/fff_logo_vector.xml       splash drawable

If FfF later supplies a vector (SVG) logo, the in-app SVGs can simply be replaced by it.
Licence: GPL-2.0-or-later, as the rest of this repository. The logo itself belongs to Foundations for Farming.
"""
import base64
import io
import os
import sys

import numpy as np
from PIL import Image, ImageDraw

if len(sys.argv) != 2:
    sys.exit(__doc__)

src = Image.open(sys.argv[1]).convert("RGB")
a = np.asarray(src).astype(int)

# 1. find the round logo: bounding box of everything that isn't near-white
ys, xs = np.where(a.min(axis=2) < 235)
x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
r = ((x1 - x0) + (y1 - y0)) / 4 - 1.5          # slightly inside the edge, to drop the white fringe

# 2. anti-aliased round mask (drawn 4x larger, then reduced)
S = 4
mask = Image.new("L", (src.width * S, src.height * S), 0)
ImageDraw.Draw(mask).ellipse([(cx - r) * S, (cy - r) * S, (cx + r) * S, (cy + r) * S], fill=255)
mask = mask.resize(src.size, Image.LANCZOS)
logo = src.convert("RGBA")
logo.putalpha(mask)
side = int(2 * r) + 4
left, top = int(cx - side / 2), int(cy - side / 2)
logo = logo.crop((left, top, left + side, top + side))


def save(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, optimize=True)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


save(logo, "branding/fff/fff_logo_round.png")

# 3. SVGs with the PNG embedded (Qt's SVG renderer supports embedded data: images)
buf = io.BytesIO()
logo.resize((384, 384), Image.LANCZOS).save(buf, "PNG", optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode()
svg = ('<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
       'width="512" height="512" viewBox="0 0 512 512">\n'
       '  <!-- Foundations for Farming logo (raster embedded). Generated by branding/fff/make_logo_assets.py -->\n'
       f'  <image x="0" y="0" width="512" height="512" xlink:href="data:image/png;base64,{b64}"/>\n'
       '</svg>\n')
for p in ("branding/fff/fff_logo.svg", "images/icons/qfieldcloud_logo.svg", "images/icons/nyuki.svg"):
    write(p, svg)

# 4. Android launcher: 108dp canvas = 432 px; safe zone 66dp = 264 px, centred
fg = Image.new("RGBA", (432, 432), (0, 0, 0, 0))
small = logo.resize((264, 264), Image.LANCZOS)
fg.paste(small, (84, 84), small)
save(fg, "platform/android/res/drawable-nodpi/fff_logo_fg.png")
save(logo.resize((480, 480), Image.LANCZOS), "platform/android/res/drawable-nodpi/fff_logo_splash.png")

d = "platform/android/res/drawable/"
write(d + "launcher_fff_logo.xml", '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/launcher_fff_logo_background" />
    <foreground android:drawable="@drawable/launcher_fff_logo_foreground" />
    <monochrome android:drawable="@drawable/launcher_fff_logo_monochrome"/>
</adaptive-icon>
''')
write(d + "launcher_fff_logo_background.xml", '''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFF" android:pathData="M0,0h108v108h-108z" />
</vector>
''')
write(d + "launcher_fff_logo_foreground.xml", '''<?xml version="1.0" encoding="utf-8"?>
<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/fff_logo_fg"
    android:gravity="fill" />
''')
# Android 13+ "themed icons" use a one-colour silhouette: the FfF water droplet
write(d + "launcher_fff_logo_monochrome.xml", '''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFF"
        android:pathData="M54,28 C54,28 39,47 39,59 A15,15 0 0 0 69,59 C69,47 54,28 54,28 Z" />
</vector>
''')
write(d + "fff_logo_vector.xml", '''<?xml version="1.0" encoding="utf-8"?>
<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/fff_logo_splash"
    android:gravity="fill" />
''')
print("FfF logo assets written")
